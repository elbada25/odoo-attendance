    def _bulk_preview_days(self) -> None:
        from datetime import timedelta
        try:
            start = dt.strptime(self._bulk_start.get().strip(), "%Y-%m-%d").date()
            end = dt.strptime(self._bulk_end.get().strip(), "%Y-%m-%d").date()
        except ValueError:
            messagebox.showerror("Error", "Formato de fecha invalido. Usa YYYY-MM-DD.")
            return
        if start > end:
            messagebox.showerror("Error", "La fecha de inicio no puede ser posterior a la de fin.")
            return

        excluded_dates = set()
        raw_exc = self._bulk_exclude.get().strip()
        if raw_exc:
            for part in raw_exc.split(","):
                part = part.strip()
                if part:
                    try:
                        excluded_dates.add(dt.strptime(part, "%Y-%m-%d").date())
                    except ValueError:
                        messagebox.showerror("Error", f"Fecha invalida: {part}")
                        return

        skip = set(self.cfg.get("behavior", {}).get("skip_weekdays", []))
        lines = []
        count = 0
        excluded_count = 0
        current = start
        while current <= end:
            if current in excluded_dates:
                lines.append(f"  {current} ({WEEKDAYS_FULL[current.weekday()]:9s})  EXCLUIDO")
                excluded_count += 1
            elif current.weekday() not in skip:
                try:
                    import odoo_attendance as _m
                    blocks = _m.get_today_blocks(current, self.cfg)
                except Exception:
                    blocks = []
                if blocks:
                    bs = ", ".join(f"{b[0]}-{b[1]} [{b[2]}]" for b in blocks)
                    lines.append(f"  {current} ({WEEKDAYS_FULL[current.weekday()]:9s})  {bs}")
                    count += 1
                else:
                    lines.append(f"  {current} ({WEEKDAYS_FULL[current.weekday()]:9s})  (sin bloques)")
            current += timedelta(days=1)

        header = f"Dias a fichar: {count}"
        if excluded_count:
            header += f"    Excluidos: {excluded_count}"
        header += f"    Rango: {start} -> {end}\n"
        header += "-" * 60 + "\n"
        self._bulk_preview.configure(state="normal")
        self._bulk_preview.delete("1.0", END)
        self._bulk_preview.insert("1.0", header + "\n".join(lines))
        self._bulk_preview.configure(state="disabled")

    def _fichar_bulk(self) -> None:
        C, F = self.C, self.F
        if self._dirty:
            if not messagebox.askyesno("Cambios sin guardar",
                "Hay cambios sin guardar. Guardar antes de fichar?"):
                return
            self._save()

        try:
            start = dt.strptime(self._bulk_start.get().strip(), "%Y-%m-%d").date()
            end = dt.strptime(self._bulk_end.get().strip(), "%Y-%m-%d").date()
        except ValueError:
            messagebox.showerror("Error", "Formato de fecha invalido.")
            return
        if start > end:
            messagebox.showerror("Error", "La fecha de inicio no puede ser posterior a la de fin.")
            return

        excluded_dates = []
        excluded_str = self._bulk_exclude.get().strip()
        if excluded_str:
            for part in excluded_str.split(","):
                part = part.strip()
                if part:
                    try:
                        excluded_dates.append(dt.strptime(part, "%Y-%m-%d").date())
                    except ValueError:
                        messagebox.showerror("Error", f"Fecha invalida: {part}")
                        return

        excluded_msg = ""
        if excluded_dates:
            excluded_msg = "\nExcluyendo: " + ", ".join(
                d.strftime("%Y-%m-%d") for d in excluded_dates)

        if not messagebox.askyesno("Fichaje en masa",
            f"Se va a fichar el rango {start} a {end}.{excluded_msg}\n\n"
            "Se registrara la asistencia via API.\n\nContinuar?"):
            return

        if not ATTENDANCE_SCRIPT.exists():
            messagebox.showerror("Error", f"No se encuentra {ATTENDANCE_SCRIPT}")
            return

        win = tk.Toplevel(self.root)
        win.title("Fichaje en masa")
        win.geometry("620x420")
        win.transient(self.root)
        win.configure(bg=C["surface"])
        txt = scrolledtext.ScrolledText(
            win, width=72, height=20, font=F["mono"],
            bg=C["code_bg"], fg=C["code_text"], relief="flat", borderwidth=0,
            padx=12, pady=12)
        txt.pack(fill=BOTH, expand=True)
        txt.insert(END, f"Fichando rango {start} a {end}...\n\n")
        txt.configure(state="disabled")

        def run() -> None:
            try:
                cmd = [str(PYTHON_EXE), str(ATTENDANCE_SCRIPT), "--bulk",
                       start.strftime("%Y-%m-%d"), end.strftime("%Y-%m-%d")]
                if excluded_dates:
                    cmd.append("--exclude")
                    cmd.append(",".join(d.strftime("%Y-%m-%d") for d in excluded_dates))
                proc = subprocess.run(
                    cmd, cwd=str(SCRIPT_DIR),
                    capture_output=True, text=True, timeout=1800,
                    startupinfo=_no_console_si())
                msg = (proc.stdout or "") + (
                    "\n--- stderr ---\n" + proc.stderr if proc.stderr else "")
                msg += f"\n[exit code {proc.returncode}]"
            except subprocess.TimeoutExpired:
                msg = "TIMEOUT."
            except Exception as exc:
                msg = f"ERROR: {exc}"
            txt.configure(state="normal")
            txt.insert(END, msg + "\n")
            txt.configure(state="disabled")
            txt.see(END)

        threading.Thread(target=run, daemon=True).start()

