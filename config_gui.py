    def _bulk_preview_days(self) -> None:
        """Show which days would be fiched without actually doing it."""
        from datetime import datetime, date, timedelta
        try:
            start = datetime.strptime(self._bulk_start.get().strip(), "%Y-%m-%d").date()
            end = datetime.strptime(self._bulk_end.get().strip(), "%Y-%m-%d").date()
        except ValueError:
            messagebox.showerror("Error", "Formato de fecha invalido. Usa YYYY-MM-DD.")
            return
        if start > end:
            messagebox.showerror("Error", "La fecha de inicio no puede ser posterior a la de fin.")
            return

        # Parse excluded dates
        excluded_dates = set()
        raw_exc = self._bulk_exclude.get().strip()
        if raw_exc:
            for part in raw_exc.split(","):
                part = part.strip()
                if part:
                    try:
                        excluded_dates.add(datetime.strptime(part, "%Y-%m-%d").date())
                    except ValueError:
                        messagebox.showerror("Error", f"Fecha de exclusion invalida: {part}")
                        return

        skip = set(self.cfg.get("behavior", {}).get("skip_weekdays", []))
        weekday_names = ["Lunes", "Martes", "Miercoles", "Jueves", "Viernes", "Sabado", "Domingo"]
        lines = []
        count = 0
        excluded_count = 0
        current = start
        while current <= end:
            if current in excluded_dates:
                lines.append(f"  {current} ({weekday_names[current.weekday()]:9s}) -> EXCLUIDO")
                excluded_count += 1
            elif current.weekday() not in skip:
                # Import get_today_blocks from odoo_attendance
                import sys as _sys
                _sys.path.insert(0, str(SCRIPT_DIR))
                try:
                    import odoo_attendance as _m
                    blocks = _m.get_today_blocks(current, self.cfg)
                except Exception:
                    blocks = []
                if blocks:
                    blocks_str = ", ".join(f"{b[0]}-{b[1]} [{b[2]}]" for b in blocks)
                    lines.append(f"  {current} ({weekday_names[current.weekday()]:9s}) -> {blocks_str}")
                    count += 1
                else:
                    lines.append(f"  {current} ({weekday_names[current.weekday()]:9s}) -> (sin bloques)")
            current += timedelta(days=1)

        header = f"Dias a fichar: {count}"
        if excluded_count:
            header += f"  (excluidos: {excluded_count})"
        header += f"  (rango {start} a {end})\n" + "-" * 60 + "\n"
        self._bulk_preview.configure(state="normal")
        self._bulk_preview.delete("1.0", END)
        self._bulk_preview.insert("1.0", header + "\n".join(lines))
        self._bulk_preview.configure(state="disabled")

    def _fichar_bulk(self) -> None:
        """Run fichaje en masa for the selected date range."""
        from datetime import datetime, date
        if self._dirty:
            if not messagebox.askyesno("Cambios sin guardar",
                "Hay cambios sin guardar. ¿Guardar antes de fichar?"):
                return
            self._save()

        try:
            start = datetime.strptime(self._bulk_start.get().strip(), "%Y-%m-%d").date()
            end = datetime.strptime(self._bulk_end.get().strip(), "%Y-%m-%d").date()
        except ValueError:
            messagebox.showerror("Error", "Formato de fecha invalido. Usa YYYY-MM-DD.")
            return
        if start > end:
            messagebox.showerror("Error", "La fecha de inicio no puede ser posterior a la de fin.")
            return

        # Parse excluded dates for the CLI call
        excluded_str = self._bulk_exclude.get().strip()
        excluded_dates = []
        if excluded_str:
            for part in excluded_str.split(","):
                part = part.strip()
                if part:
                    try:
                        excluded_dates.append(datetime.strptime(part, "%Y-%m-%d").date())
                    except ValueError:
                        messagebox.showerror("Error", f"Fecha de exclusion invalida: {part}")
                        return

        excluded_msg = ""
        if excluded_dates:
            excluded_msg = f"\nExcluyendo: {', '.join(d.strftime('%Y-%m-%d') for d in excluded_dates)}"

        if not messagebox.askyesno(
            "Fichaje en masa",
            f"Se va a fichar el rango {start} a {end}.{excluded_msg}\n\n"
            "Esto abrira Chrome y registrara la asistencia de cada dia\n"
            "laborable secuencialmente. Puede tardar varios minutos.\n\n"
            "¿Continuar?",
        ):
            return

        if not ATTENDANCE_SCRIPT.exists():
            messagebox.showerror("Error", f"No se encuentra {ATTENDANCE_SCRIPT}")
            return

        win = tk.Toplevel(self.root)
        win.title("Fichaje en masa en progreso...")
        win.geometry("600x400")
        win.transient(self.root)
        txt = scrolledtext.ScrolledText(win, width=74, height=22,
            font=("Consolas", 9) if os.name == "nt" else ("Mono", 9))
        txt.pack(fill=BOTH, expand=True, padx=8, pady=8)
        txt.insert(END, f"Fichando rango {start} a {end}...\n\n")
        txt.configure(state="disabled")

        def run() -> None:
            try:
                cmd = [str(PYTHON_EXE), str(ATTENDANCE_SCRIPT), "--bulk",
                       start.strftime("%Y-%m-%d"), end.strftime("%Y-%m-%d")]
                if excluded_dates:
                    cmd.append("--exclude")
                    cmd.append(",".join(d.strftime("%Y-%m-%d") for d in excluded_dates))
                proc = subprocess.run(
                    cmd,
                    cwd=str(SCRIPT_DIR),
                    capture_output=True,
                    text=True,
                    timeout=1800,
                )
                msg = (proc.stdout or "") + ("\n--- stderr ---\n" + proc.stderr if proc.stderr else "")
                msg += f"\n[exit code {proc.returncode}]"
            except subprocess.TimeoutExpired:
                msg = "TIMEOUT: el script tardó demasiado."
            except Exception as exc:
                msg = f"ERROR: {exc}"
            txt.configure(state="normal")
            txt.insert(END, msg + "\n")
            txt.configure(state="disabled")
            txt.see(END)

        threading.Thread(target=run, daemon=True).start()

    def _mark_dirty(self, *_args) -> None:
        self._dirty = True

    def _collect(self) -> dict:
        cfg = default_config()
        cfg["odoo"]["url"] = self._url.get().strip()
        cfg["odoo"]["username"] = self._user.get().strip()
        cfg["odoo"]["password"] = self._pass.get().strip()
        cfg["odoo"]["headless"] = self._headless.get()
        cfg["odoo"]["user_data_dir"] = self._udd.get().strip()
        cfg["behavior"]["enabled"] = self._enabled.get()
        cfg["behavior"]["skip_weekdays"] = [i for i, v in enumerate(self._skip_vars) if v.get()]
        sm_raw = [m.strip() for m in self._summer_months.get().split(",") if m.strip()]
        try:
            cfg["schedule"]["summer_months"] = [int(m) for m in sm_raw]
        except ValueError:
            cfg["schedule"]["summer_months"] = []
        for kind in ("normal", "summer"):
            cfg["schedule"][kind] = {
                str(i): self._day_editors[kind][str(i)].get_blocks() for i in range(7)
            }
        cfg["schedule"]["special_days"] = {
            k: ed.get_blocks() for k, ed in self._special_editors.items()
        }
        return cfg

    def _save(self) -> None:
        cfg = self._collect()
        try:
            save_config(cfg)
        except Exception as exc:  # noqa: BLE001
            messagebox.showerror("Error al guardar", str(exc))
            return
        self.cfg = cfg
        self._dirty = False
        messagebox.showinfo("Guardado", f"Configuraci\u00f3n guardada en:\n{CONFIG_PATH}")

