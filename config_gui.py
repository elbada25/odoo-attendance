def _no_console_si():
    if os.name == "nt":
        si = subprocess.STARTUPINFO()  # type: ignore[attr-defined]
        si.dwFlags |= subprocess.STARTF_USESHOWWINDOW  # type: ignore[attr-defined]
        si.wShowWindow = subprocess.SW_HIDE  # type: ignore[attr-defined]
        return si
    return None


