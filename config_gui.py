    def _build_schedule(self, parent, kind: str) -> None:
        canvas = tk.Canvas(parent, borderwidth=0, highlightthickness=0)
        scroll = ttk.Scrollbar(parent, orient="vertical", command=canvas.yview)
        inner = ttk.Frame(canvas)
        inner.bind(
            "<Configure>",
            lambda e: canvas.configure(scrollregion=canvas.bbox("all")),
        )
        canvas.create_window((0, 0), window=inner, anchor="nw")
        canvas.configure(yscrollcommand=scroll.set)
        canvas.pack(side=LEFT, fill=BOTH, expand=True)
        scroll.pack(side=RIGHT, fill=Y)

        self._day_editors: dict[str, dict[str, DayEditor]] = getattr(self, "_day_editors", {})
        self._day_editors[kind] = {}
        days = self.cfg["schedule"].get(kind, {})
        for i in range(7):
            blocks = days.get(str(i), [])
            ed = DayEditor(inner, WEEKDAYS_ES[i], blocks, self._mark_dirty)
            ed.pack(fill=X, padx=6, pady=4)
            self._day_editors[kind][str(i)] = ed

        # Mouse wheel scrolling
        def _wheel(event):
            canvas.yview_scroll(int(-1 * (event.delta / 120)), "units")
        canvas.bind_all("<MouseWheel>", _wheel)

