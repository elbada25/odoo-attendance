    def _nav_hover(self, key: str, enter: bool) -> None:
        C = self.C
        if key == self._current_nav:
            return
        bg = C["nav_hov"] if enter else C["nav_bg"]
        btn = self._nav_buttons[key]
        lbl = self._nav_labels[key]
        ind = self._nav_indicators[key]
        btn.configure(bg=bg)
        lbl.configure(bg=bg)
        ind.configure(bg=bg)

    def _make_scrollable_page(self, key: str) -> tuple[tk.Frame, ttk.Frame]:
        """Create a scrollable page.

        Returns (container, inner): the container is packed/unpacked to
        show/hide the page; the inner frame is where content is built.
        """
        C = self.C
        container = tk.Frame(self._content_area, bg=C["surface"])
        container.pack(fill=BOTH, expand=True)
        container.pack_forget()  # hidden until selected

        canvas = tk.Canvas(container, bg=C["surface"], borderwidth=0,
                           highlightthickness=0)
        scroll = ModernScrollbar(container, canvas.yview, C)
        inner = ttk.Frame(canvas, style="Surface.TFrame")
        inner.bind("<Configure>",
                   lambda e: canvas.configure(scrollregion=canvas.bbox("all")))
        win_id = canvas.create_window((0, 0), window=inner, anchor="nw")
        canvas.configure(yscrollcommand=scroll.set)
        # Pack scrollbar FIRST so canvas fills the remaining space
        scroll.pack(side=RIGHT, fill=Y)
        canvas.pack(side=LEFT, fill=BOTH, expand=True)
        self._canvases.append(canvas)

        def _on_resize(event):
            canvas.itemconfigure(win_id, width=event.width)
        canvas.bind("<Configure>", _on_resize)

        return container, inner

    def _show_page(self, key: str) -> None:
        C = self.C
        # Hide all page containers
        for page in self._pages.values():
            page.pack_forget()

        # Show selected
        self._pages[key].pack(fill=BOTH, expand=True)

        # Update nav styles
        for k, _ in NAV_ITEMS:
            is_active = (k == key)
            btn = self._nav_buttons[k]
            lbl = self._nav_labels[k]
            ind = self._nav_indicators[k]
            if is_active:
                btn.configure(bg=C["nav_active"])
                lbl.configure(bg=C["nav_active"], fg=C["text"],
                              font=self.F["nav_active"])
                ind.configure(bg=C["nav_indicator"])
            else:
                btn.configure(bg=C["nav_bg"])
                lbl.configure(bg=C["nav_bg"], fg=C["text_sec"],
                              font=self.F["nav"])
                ind.configure(bg=C["nav_bg"])

        self._current_nav = key

    def _on_mousewheel(self, event) -> None:
        for canvas in self._canvases:
            try:
                if canvas.winfo_ismapped():
                    canvas.yview_scroll(int(-1 * (event.delta / 120)), "units")
                    return
            except Exception:
                pass

