def load_config() -> dict:
    path = CONFIG_PATH if CONFIG_PATH.exists() else EXAMPLE_PATH
    if path.exists():
        with open(path, "rb") as fh:
            cfg = tomllib.load(fh)
        base = default_config()
        base["odoo"].update(cfg.get("odoo", {}))
        base["behavior"].update(cfg.get("behavior", {}))
        sched = cfg.get("schedule", {})
        base["schedule"]["summer_months"] = sched.get("summer_months", [7, 8])
        for kind in ("summer", "normal"):
            base["schedule"][kind] = {
                str(i): [tuple(b) for b in sched.get(kind, {}).get(str(i), [])]
                for i in range(7)
            }
        base["schedule"]["special_days"] = {
            k: [tuple(b) for b in v]
            for k, v in sched.get("special_days", {}).items()
        }
        return base
    return default_config()


def _fmt_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def save_config(cfg: dict) -> None:
    odoo = cfg["odoo"]
    beh = cfg["behavior"]
    sched = cfg["schedule"]

    def block_str(blocks: list) -> str:
        if not blocks:
            return "[]"
        return "[" + ", ".join(
            f"[{_fmt_str(b[0])}, {_fmt_str(b[1])}, {_fmt_str(b[2])}]" for b in blocks
        ) + "]"

    lines = [
        "# Odoo Attendance - Configuration (generated by config_gui.py)",
        "",
        "[odoo]",
        f"url = {_fmt_str(str(odoo.get('url', '')))}",
        f"username = {_fmt_str(str(odoo.get('username', '')))}",
        f"password = {_fmt_str(str(odoo.get('password', '')))}",
        f"headless = {str(bool(odoo.get('headless', False))).lower()}",
        f"user_data_dir = {_fmt_str(str(odoo.get('user_data_dir', '')))}",
        "",
        "[behavior]",
        f"enabled = {str(bool(beh.get('enabled', True))).lower()}",
        f"skip_weekdays = [{', '.join(str(int(x)) for x in beh.get('skip_weekdays', []))}]",
        f"check_updates = {str(bool(beh.get('check_updates', True))).lower()}",
        f"minimize_to_tray = {str(bool(beh.get('minimize_to_tray', False))).lower()}",
        f"auto_fichaje = {str(bool(beh.get('auto_fichaje', False))).lower()}",
        f"auto_fichaje_time = {_fmt_str(str(beh.get('auto_fichaje_time', '08:00')))}",
        f"auto_fichaje_headless = {str(bool(beh.get('auto_fichaje_headless', True))).lower()}",
        f"reminder_enabled = {str(bool(beh.get('reminder_enabled', False))).lower()}",
        f"reminder_time = {_fmt_str(str(beh.get('reminder_time', '09:30')))}",
        "",
        "[schedule]",
        f"summer_months = [{', '.join(str(int(x)) for x in sched.get('summer_months', []))}]",
    ]
    for kind, label in (("summer", "summer / intensive"), ("normal", "normal")):
        lines += ["", f"# {label} schedule  (0=Monday ... 6=Sunday)",
                  f"[schedule.{kind}]"]
        for i in range(7):
            lines.append(f"{i} = {block_str(sched.get(kind, {}).get(str(i), []))}")
    lines += ["", '# Special days  (key = "MM-DD")',
              "[schedule.special_days]"]
    sd = sched.get("special_days", {})
    if sd:
        for k in sorted(sd.keys()):
            lines.append(f'{_fmt_str(k)} = {block_str(sd[k])}')
    else:
        lines.append("# (none)")
    lines.append("")
    CONFIG_PATH.write_text("\n".join(lines), encoding="utf-8")


