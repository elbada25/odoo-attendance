class DayEditor(ttk.Frame):
    """Editor for a single weekday's time blocks."""

    def __init__(self, master, weekday_name: str, blocks: list,
                 on_change, C, F):
        super().__init__(master, style="Surface.TFrame")
        self.C = C
        self.F = F
        self._on_change = on_change
        self._rows = []

        if weekday_name:
            ttk.Label(self, text=weekday_name, font=F["body_b"],
                      style="Surface.TLabel").pack(anchor="w", pady=(0, 6))

        self._table = ttk.Frame(self, style="Surface.TFrame")
        self._table.pack(fill=X)

        for c, txt in enumerate(["Entrada", "Salida", "Categoria"]):
            ttk.Label(self._table, text=txt, font=F["small"],
                      foreground=C["text_sec"],
                      style="Surface.TLabel").grid(
                row=0, column=c, padx=(0, 12), sticky="w")

        for b in blocks:
            self._add_row(b)

        ModernButton(self, "+ Anadir bloque", C, F,
                     command=lambda: self._add_row(["09:00", "14:00", "Trabajo"]),
                     padx=12, pady=6).pack(anchor="w", pady=(8, 0))

    def _add_row(self, block) -> None:
        r = len(self._rows) + 1
        in_var = StringVar(value=block[0])
        out_var = StringVar(value=block[1])
        cat_var = StringVar(value=block[2])
        e1 = TimeEntry(self._table, in_var, self.C, self.F, width=7)
        e2 = TimeEntry(self._table, out_var, self.C, self.F, width=7)
        e3 = ModernEntry(self._table, self.C, self.F, textvariable=cat_var,
                         width=16)
        for w, var, col in ((e1, in_var, 0), (e2, out_var, 1), (e3, cat_var, 2)):
            w.grid(row=r, column=col, padx=(0, 12), pady=3)
            var.trace_add("write", lambda *_: self._on_change())
        del_btn = tk.Button(
            self._table, text="\u2715", width=3,
            relief="flat", bd=0,
            bg=self.C["surface2"], fg=self.C["text_sec"],
            activebackground=self.C["surface3"],
            font=self.F["small"],
            highlightthickness=0,
            command=lambda: self._del_row(r))
        del_btn.grid(row=r, column=3, padx=0)
        self._rows.append([e1, e2, e3, del_btn, in_var, out_var, cat_var])

    def _del_row(self, row_idx: int) -> None:
        for i, row in enumerate(self._rows):
            if row[3].grid_info().get("row") == row_idx:
                for w in row[:4]:
                    if w:
                        w.destroy()
                self._rows.pop(i)
                self._on_change()
                return

    def get_blocks(self) -> list[list[str]]:
        result = []
        for row in self._rows:
            cin = row[4].get().strip()
            cout = row[5].get().strip()
            cat = row[6].get().strip()
            if cin or cout or cat:
                result.append([cin, cout, cat])
        return result


