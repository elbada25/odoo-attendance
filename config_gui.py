def load_config() -> dict:
    path = CONFIG_PATH if CONFIG_PATH.exists() else EXAMPLE_PATH
    if path.exists():
        with open(path, "rb") as fh:
            cfg = tomllib.load(fh)
        # Fill missing keys so the GUI always has something to show.
        base = default_config()
        base["odoo"].update(cfg.get("odoo", {}))
        base["behavior"].update(cfg.get("behavior", {}))
        sched = cfg.get("schedule", {})
        base["schedule"]["summer_months"] = sched.get("summer_months", [7, 8])
        for kind in ("summer", "normal"):
            base["schedule"][kind] = {
                str(i): [tuple(b) for b in sched.get(kind, {}).get(str(i), [])]
                for i in range(7)
            }
        base["schedule"]["special_days"] = {
            k: [tuple(b) for b in v] for k, v in sched.get("special_days", {}).items()
        }
        return base
    return default_config()


def _fmt_str(s: str) -> str:
    """Quote a TOML basic string, escaping backslashes and quotes."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def save_config(cfg: dict) -> None:
    """Write config.toml by hand (stdlib has no TOML writer)."""
    odoo = cfg["odoo"]
    beh = cfg["behavior"]
    sched = cfg["schedule"]

    def day_block_lines(blocks: list, indent: str) -> str:
        if not blocks:
            return "[]"
        inner = ", ".join(f"[{_fmt_str(b[0])}, {_fmt_str(b[1])}, {_fmt_str(b[2])}]" for b in blocks)
        return f"[{inner}]"

    lines: list[str] = []
    lines.append("# Odoo Attendance - Configuration (generated by config_gui.py)")
    lines.append("")
    lines.append("[odoo]")
    lines.append(f"url = {_fmt_str(str(odoo.get('url', '')))}")
    lines.append(f"username = {_fmt_str(str(odoo.get('username', '')))}")
    lines.append(f"password = {_fmt_str(str(odoo.get('password', '')))}")
    lines.append(f"headless = {str(bool(odoo.get('headless', False))).lower()}")
    lines.append(f"user_data_dir = {_fmt_str(str(odoo.get('user_data_dir', '')))}")
    lines.append("")
    lines.append("[behavior]")
    lines.append(f"enabled = {str(bool(beh.get('enabled', True))).lower()}")
    skip = beh.get("skip_weekdays", [])
    lines.append(f"skip_weekdays = [{', '.join(str(int(x)) for x in skip)}]")
    lines.append("")
    lines.append("[schedule]")
    sm = sched.get("summer_months", [])
    lines.append(f"summer_months = [{', '.join(str(int(x)) for x in sm)}]")
    for kind, label in (("summer", "summer / intensive"), ("normal", "normal")):
        lines.append("")
        lines.append(f"# {label} schedule  (0=Monday ... 6=Sunday)")
        lines.append(f"[schedule.{kind}]")
        for i in range(7):
            blocks = sched.get(kind, {}).get(str(i), [])
            lines.append(f"{i} = {day_block_lines(blocks, '')}")
    lines.append("")
    lines.append('# Special days  (key = "MM-DD")')
    lines.append("[schedule.special_days]")
    sd = sched.get("special_days", {})
    if sd:
        for k in sorted(sd.keys()):
            lines.append(f'{_fmt_str(k)} = {day_block_lines(sd[k], "")}')
    else:
        lines.append("# (none)")
    lines.append("")
    CONFIG_PATH.write_text("\n".join(lines), encoding="utf-8")


