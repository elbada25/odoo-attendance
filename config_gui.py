class DayEditor(ttk.Frame):
    """Editor for a single weekday: a list of [in, out, category] blocks."""

    def __init__(self, master, weekday_name: str, blocks: list, on_change):
        super().__init__(master, borderwidth=1, relief="groove", padding=6)
        self._on_change = on_change
        self._rows: list[list[tk.Widget]] = []

        header = ttk.Label(self, text=weekday_name, font=("Segoe UI", 10, "bold") if os.name == "nt" else ("Sans", 10, "bold"))
        header.pack(anchor="w")

        self._table = ttk.Frame(self)
        self._table.pack(fill=X)

        # Column headers
        for c, txt in enumerate(["Entrada", "Salida", "Categor\u00eda", ""]):
            ttk.Label(self._table, text=txt).grid(row=0, column=c, padx=4, sticky="w")

        for b in blocks:
            self._add_row(b)

        add_btn = ttk.Button(self, text="+ A\u00f1adir bloque", width=16, command=lambda: self._add_row(["09:00", "14:00", "Trabajo"]))
        add_btn.pack(anchor="w", pady=(4, 0))

    def _add_row(self, block) -> None:
        r = len(self._rows) + 1
        in_var = StringVar(value=block[0])
        out_var = StringVar(value=block[1])
        cat_var = StringVar(value=block[2])
        e1 = ttk.Entry(self._table, textvariable=in_var, width=8)
        e2 = ttk.Entry(self._table, textvariable=out_var, width=8)
        e3 = ttk.Entry(self._table, textvariable=cat_var, width=12)
        for w, var in ((e1, in_var), (e2, out_var), (e3, cat_var)):
            w.grid(row=r, column=0 if w is e1 else 1 if w is e2 else 2, padx=4, pady=2)
            var.trace_add("write", lambda *_: self._on_change())
        del_btn = ttk.Button(self._table, text="X", width=3, command=lambda: self._del_row(r))
        del_btn.grid(row=r, column=3, padx=2)
        self._rows.append([e1, e2, e3, del_btn, in_var, out_var, cat_var])

    def _del_row(self, row_idx: int) -> None:
        # row_idx is 1-based grid row; find matching entry
        for i, row in enumerate(self._rows):
            if row[3].grid_info().get("row") == row_idx:
                for w in row[:4]:
                    w.destroy()
                self._rows.pop(i)
                self._on_change()
                return

    def get_blocks(self) -> list[list[str]]:
        result = []
        for row in self._rows:
            cin = row[4].get().strip()
            cout = row[5].get().strip()
            cat = row[6].get().strip()
            if cin or cout or cat:
                result.append([cin, cout, cat])
        return result


